test('--open uses literal configured executables and the vscode default; failures retain preparation', { skip: process.platform !== 'darwin' }, async t => {
  const root = fixture(t), file = path.join(root, '.agentflow/ag.json')
  const config = JSON.parse(fs.readFileSync(file)), capture = path.join(root, 'editor-args.json')
  const editor = path.join(root, 'editor space ; $(touch forbidden)')
  fs.writeFileSync(editor, `#!${process.execPath}\nrequire('node:fs').writeFileSync(${JSON.stringify(capture)}, JSON.stringify(process.argv.slice(2)))\n`, { mode: 0o700 })
  config['default-editor'] = editor
  fs.writeFileSync(file, JSON.stringify(config))
  C.git(root, ['add', '--', '.agentflow/ag.json']); C.git(root, ['commit', '-m', 'custom editor'])
  const result = await F.create('editor', { cwd: root, open: true })
  assert.deepEqual(JSON.parse(fs.readFileSync(capture)), [path.join(result.destination, '.agentflow/features/editor/editor.devlog.md')])
  assert.equal(fs.existsSync(path.join(result.destination, 'forbidden')), false)
  assert.doesNotMatch(result.message, /did not open/)
  const bin = path.join(root, 'bin'); fs.mkdirSync(bin)
  fs.copyFileSync(editor, path.join(bin, 'code')); fs.chmodSync(path.join(bin, 'code'), 0o700)
  const before = process.env.PATH
  try {
    process.env.PATH = bin + path.delimiter + before
    for (const value of [undefined, 'vscode']) {
      if (value === undefined) delete config['default-editor']; else config['default-editor'] = value
      fs.writeFileSync(file, JSON.stringify(config))
      C.git(root, ['add', '--', '.agentflow/ag.json']); C.git(root, ['commit', '--allow-empty', '-m', 'default editor'])
      const r = await F.create(value ? 'explicit' : 'omitted', { cwd: root, open: true })
      assert.deepEqual(JSON.parse(fs.readFileSync(capture)), [path.join(r.destination, `.agentflow/features/${value ? 'explicit' : 'omitted'}/${value ? 'explicit' : 'omitted'}.devlog.md`)])
    }
  } finally { process.env.PATH = before }
  fs.writeFileSync(editor, `#!${process.execPath}\nprocess.exit(7)\n`)
  config['default-editor'] = editor; fs.writeFileSync(file, JSON.stringify(config))
  C.git(root, ['add', '--', '.agentflow/ag.json']); C.git(root, ['commit', '-m', 'failing editor'])
  const failed = await F.create('nonzero', { cwd: root, open: true })
  assert.match(failed.message, /Editor did not open \(7\); feature preparation succeeded/)
  assert.ok(fs.existsSync(failed.destination))
})
