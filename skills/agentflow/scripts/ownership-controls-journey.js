#!/usr/bin/env node
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync, execFileSync } = require('node:child_process');
assert.ok(process.stdin.isTTY && process.stdout.isTTY, 'Run this journey in a real terminal/PTY');
console.log('Terminal: ' + execFileSync('tty', { stdio: ['inherit', 'pipe', 'inherit'], encoding: 'utf8' }).trim());
const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'agf-ownership-pty-')));
const notebook = '.agentflow/devlog.md';
const settings = require('./ag-settings');
settings.initialize_project({ repo_root: root, active_host: 'portable' });
require('./agf').update_ignore_file(root);
const git = args => execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
git(['init', '-q', '-b', 'main']);
git(['config', 'user.name', 'Ownership journey']);
git(['config', 'user.email', 'ownership@example.invalid']);
git(['add', '.']); git(['commit', '-qm', 'baseline']);
const config_path = path.join(root, 'ag.json');
const policy = value => {
  const args = ['change', '--repo', root, '--notebook', notebook, '--host', 'portable', '--set', 'notebook-ownership: ' + value];
  console.log('$ node ag-settings.js ' + args.join(' '));
  const child = spawnSync(process.execPath, [path.join(__dirname, 'ag-settings.js'), ...args], { cwd: root, encoding: 'utf8', timeout: 30000 });
  process.stdout.write(child.stdout || ''); process.stderr.write(child.stderr || '');
  console.log('Exit: ' + child.status);
  assert.equal(child.status, 0, child.error?.message);
  assert.equal(JSON.parse(fs.readFileSync(config_path)).switches['notebook-ownership'], value);
  const shown = spawnSync(process.execPath, [path.join(__dirname, 'ag-settings.js'), 'show', '--repo', root, '--notebook', notebook, '--host', 'portable'], { cwd: root, encoding: 'utf8', timeout: 30000 });
  console.log('$ node ag-settings.js show --repo ' + root + ' --notebook ' + notebook + ' --host portable');
  process.stdout.write(shown.stdout || ''); process.stderr.write(shown.stderr || '');
  console.log('Exit: ' + shown.status);
  assert.equal(shown.status, 0);
  assert.match(shown.stdout, new RegExp('notebook-ownership: ' + value));
};
const run = (session, input, expected = 0) => {
  const args = ['append-input', '--host', 'portable', '--session', session, '--notebook', notebook, '--input-stdin'];
  console.log('$ node notebook-write.js ' + args.join(' '));
  console.log('stdin: ' + input);
  const child = spawnSync(process.execPath, [path.join(__dirname, 'notebook-write.js'), ...args], { cwd: root, input, encoding: 'utf8', timeout: 30000 });
  process.stdout.write(child.stdout || ''); process.stderr.write(child.stderr || '');
  console.log('Exit: ' + child.status);
  assert.equal(child.status, expected, child.error?.message);
};
policy('on');
run('session-a', 'first owner request');
const owner = require('./notebook-owner');
const info = owner.location({ root, notebook, record_aware: true });
const bytes = fs.readFileSync(info.file);
const before = fs.readFileSync(path.join(root, notebook));
run('session-b', 'foreign request must refuse', 1);
assert.deepEqual(fs.readFileSync(path.join(root, notebook)), before);
policy('off');
run('session-b', 'second session request with ownership off');
run('session-c', 'third session request with ownership off');
assert.deepEqual(fs.readFileSync(info.file), bytes);
policy('on');
const after_off = fs.readFileSync(path.join(root, notebook));
run('session-b', 're-enabled foreign request must refuse', 1);
assert.deepEqual(fs.readFileSync(path.join(root, notebook)), after_off);
assert.deepEqual(fs.readFileSync(info.file), bytes);
console.log('Git baseline: ' + git(['rev-parse', 'HEAD']));
console.log('Git status: ' + git(['status', '--porcelain']));
assert.equal(git(['remote']), '');
console.log('PASS: on refuses another session; off permits two sessions; re-enabling refuses; retained ownership metadata stays byte-identical; no remote.');
console.log('Fixture retained: ' + root);
